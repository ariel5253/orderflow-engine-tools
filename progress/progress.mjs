#!/usr/bin/env node
// Renders handoff/progress.svg from the task table in handoff/HANDOFF.md, the only place where state lives.
// check-docs imports renderProgress() and fails when the stored SVG differs from the table.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const STATUS = {
  done: { fill: '#16a34a', stroke: '#15803d', label: 'done' },
  doing: { fill: '#0284c7', stroke: '#0369a1', label: 'in progress' },
  todo: { fill: '#ffffff', stroke: '#94a3b8', label: 'to do' },
};

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

export function parseHandoff(text) {
  const start = (text.match(/Project start:\s*(\d{4}-\d{2}-\d{2})/) || [])[1];
  const cut = (text.match(/Cut line after:\s*(T-\d\d)/) || [])[1];
  const tasks = [];
  for (const m of text.matchAll(/^\|\s*(T-\d\d)\s*\|\s*([^|]+?)\s*\|\s*(D\d)\s*\|\s*(done|doing|todo)\s*\|\s*([^|]*?)\s*\|\s*$/gm)) {
    tasks.push({ id: m[1], title: m[2].trim(), planned: Number(m[3].slice(1)), status: m[4], date: m[5].trim() });
  }
  if (!start || !cut || tasks.length === 0) throw new Error('HANDOFF task table, project start or cut line not found');
  return { start, cut, tasks };
}

const dayOf = (start, date) => Math.floor((Date.parse(date) - Date.parse(start)) / 86400000) + 1;

export function renderProgress(text) {
  const { start, cut, tasks } = parseHandoff(text);
  const W = 920;
  const rowH = 26;
  const top = 128;
  const H = top + tasks.length * rowH + 64;
  const done = tasks.filter((t) => t.status === 'done').length;
  const pct = Math.round((done / tasks.length) * 100);
  const barX = 520;
  const barW = 300;
  const out = [];
  out.push(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}" role="img" aria-label="Task progress: ${done} of ${tasks.length} tasks done (${pct}%)" font-family="ui-sans-serif, system-ui, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif">`);
  out.push(`  <title>Task progress</title>`);
  out.push(`  <rect x="0.5" y="0.5" width="${W - 1}" height="${H - 1}" rx="12" fill="#ffffff" stroke="#cbd5e1"/>`);
  out.push(`  <text x="${W / 2}" y="34" text-anchor="middle" font-size="15" font-weight="600" fill="#0f172a">Task progress: ${done} of ${tasks.length} done (${pct}%)</text>`);
  out.push(`  <text x="${W / 2}" y="54" text-anchor="middle" font-size="11.5" fill="#475569">Generated from the task table in HANDOFF.md. Project start ${esc(start)}. Planned day vs the day each task was done</text>`);
  out.push(`  <rect x="24" y="72" width="${W - 48}" height="14" rx="7" fill="#f1f5f9" stroke="#cbd5e1"/>`);
  if (done > 0) out.push(`  <rect x="24" y="72" width="${Math.max(14, Math.round(((W - 48) * done) / tasks.length))}" height="14" rx="7" fill="#16a34a"/>`);
  out.push(`  <text x="24" y="114" font-size="11" font-weight="600" fill="#0369a1">Task</text>`);
  out.push(`  <text x="440" y="114" font-size="11" font-weight="600" fill="#0369a1">Planned</text>`);
  out.push(`  <text x="${barX}" y="114" font-size="11" font-weight="600" fill="#0369a1">Status</text>`);
  out.push(`  <text x="${barX + barW + 16}" y="114" font-size="11" font-weight="600" fill="#0369a1">Done</text>`);
  tasks.forEach((t, i) => {
    const y = top + i * rowH;
    const s = STATUS[t.status];
    const late = t.status === 'done' && t.date && dayOf(start, t.date) > t.planned;
    out.push(`  <text x="24" y="${y + 16}" font-size="11.5" fill="#0f172a"><tspan font-weight="600">${t.id}</tspan> ${esc(t.title)}</text>`);
    out.push(`  <text x="440" y="${y + 16}" font-size="11.5" fill="#475569">D${t.planned}</text>`);
    const width = t.status === 'done' ? barW : t.status === 'doing' ? barW / 2 : barW;
    out.push(`  <rect x="${barX}" y="${y + 5}" width="${barW}" height="14" rx="4" fill="#f8fafc" stroke="#cbd5e1"/>`);
    if (t.status !== 'todo') out.push(`  <rect x="${barX}" y="${y + 5}" width="${width}" height="14" rx="4" fill="${s.fill}" stroke="${s.stroke}"/>`);
    out.push(`  <text x="${barX + 8}" y="${y + 16}" font-size="10" fill="${t.status === 'todo' ? '#475569' : '#ffffff'}">${s.label}</text>`);
    if (t.status === 'done') {
      const d = dayOf(start, t.date);
      out.push(`  <text x="${barX + barW + 16}" y="${y + 16}" font-size="11.5" fill="${late ? '#b45309' : '#15803d'}">D${d}${late ? ' (late)' : ''}</text>`);
    }
    if (t.id === cut) {
      const ly = y + rowH;
      out.push(`  <line x1="24" y1="${ly}" x2="${W - 24}" y2="${ly}" stroke="#dc2626" stroke-width="1.2" stroke-dasharray="6 4"/>`);
      out.push(`  <text x="${W - 24}" y="${ly - 3}" text-anchor="end" font-size="10" fill="#b91c1c">MVP cut line</text>`);
    }
  });
  out.push(`  <text x="${W - 24}" y="${H - 16}" text-anchor="end" font-size="10" fill="#475569">Generated by orderflow-engine-tools/progress/progress.mjs</text>`);
  out.push('</svg>');
  return out.join('\n') + '\n';
}

const isCli = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isCli) {
  const docsRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', 'orderflow-engine-docs');
  const handoff = readFileSync(join(docsRoot, 'handoff', 'HANDOFF.md'), 'utf8').replace(/\r\n/g, '\n');
  writeFileSync(join(docsRoot, 'handoff', 'progress.svg'), renderProgress(handoff));
  console.log('progress.svg written');
}
